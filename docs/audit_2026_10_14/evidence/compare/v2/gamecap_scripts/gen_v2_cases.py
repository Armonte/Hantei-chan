#!/usr/bin/env python3
"""v2 capture scripts (cases/v2_<game>_<chr>.gcs) from s1_compare/cases.txt: UNI2-IM pause/step, full frames."""
import collections, os, re
CASES = '/mnt/c/dev/hantei-chan/wt/render-match/tools/uni/s1_compare/cases.txt'
D = os.path.dirname(os.path.abspath(__file__))
by = collections.OrderedDict()
# frame durations (ha6_dump) of the --tick cases' patterns, frames before the case frame
DUR = {(0, 72): [5], (19, 62): [3, 5], (20, 435): [55], (20, 437): [5]}
for ln in open(CASES, encoding='utf-8'):
    if ln.startswith('#') or not ln.strip(): continue
    f = [x.strip() for x in ln.split('|')]
    name, txt, pat, fr, tick = f[0], f[1], int(f[2]), int(f[3]), int(f[4])
    if not txt.startswith('uni2/'): continue
    chr_ = int(re.search(r'chr(\d+)', txt).group(1))
    by.setdefault(chr_, []).append((name, pat, fr, tick))
for chr_, cs in by.items():
    out = ['# generated by gen_v2_cases.py - do not edit', 'include ../games/uni2.gcs', 'let P1CHR %d' % chr_, 'let P2CHR 0',
           'include ../games/uni2_to_training.gcs', r'set OUTD C:\dev\hantei-chan\tools\gamecap\captures\v2']
    for name, pat, fr, tick in cs:
        if tick < 0: setf, steps, g = fr, 1, 1
        else:  # editor --tick = global tick from the pattern start (game tick = editor tick + 1, see uni2_force_pattern.gcs)
            setf, steps = 0, tick + 1
            start = sum(DUR[(chr_, pat)][:fr]); g = tick - start + 1
        out += ['', 'set CASE ' + name, 'set PAT %d' % pat, 'set SETFRAME %d' % setf, 'set FRAME %d' % fr, 'set GTICK %d' % g,
                'set STEPKEYS ' + ','.join(['F6'] * steps), 'include ../games/uni2_v2_case.gcs']
    out.append('quit')
    open(os.path.join(D, 'cases', 'v2_uni2_chr%03d.gcs' % chr_), 'w').write('\n'.join(out) + '\n')
    print('v2_uni2_chr%03d.gcs' % chr_, [c[0] for c in cs])
