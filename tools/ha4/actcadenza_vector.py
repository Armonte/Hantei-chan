#!/usr/bin/env python3
"""ActCadenza (Ver.1.03A) VECTOR.TXT -> MBAACC-syntax vector_ac.txt (data only).

usage: actcadenza_vector.py IN OUT [--selftest]

IDA finding: MBAACC does NOT read VectorList.txt (no such string in MBAA.exe; it is an
editor source). The runtime file is data\\vector.txt (data\\old\\vector.txt with the old
option), read by VectorConfig_LoadFromFile 0x44ACB0 -> VectorConfig_ParseSubVectorTable
0x44A510 / VectorConfig_ParseHitVectorTable 0x44A800 / VectorConfig_ParseGlobalSettings
0x44ADF0 / VectorConfig_ParseDefaultPairSettings 0x44AE50. ActCadenza reads data\\vector.txt
in HitVector_LoadVectorTxt 0x445890. Both use the same positional text format and the same
records (16 B {x, y, addX, addY} ints; 172 B hit-vector records, 32 B name + 5 ints +
N x 6 ints, decimal-digit flag field), so no unit conversion is needed:

  section 1  "id x y addX addY"                                    ... END
  section 2  "id name Num UkemiTime Prio PrioAni KoCheck"
             Num x "VecNum HitAni GuardAni Time VecTime flags"     ... END
  section 3  7 hit-stop ints (weak mid strong none big huge tiny)
             wall recoil X; MBAACC also reads a second value (recoil while down) that
             defaults to the first when missing/0 -- ActCadenza has one value, so the
             output writes it twice.
  END

The values are ActCadenza's as its own sscanf parser sees them. sscanf "%d" skips
newlines, so a header line with fewer than 5 ints takes the missing ones from the next
line (ActCadenza row 11 "1 30 100 0" -> KoCheck 11); the output writes them explicitly.
HitAni/GuardAni are ActCadenza pattern numbers (MBAACC's own file uses 900+ / 300+ ids),
kept as-is: the reader hook (not this tool) decides how they map.
"""
import re
import sys

INT = re.compile(rb'[ \t\r\n]*([+-]?\d+)')


def scan_ints(t, pos, n):
    """C sscanf("%d" * n) from pos: whitespace incl. newlines is skipped."""
    vals = []
    while len(vals) < n:
        m = INT.match(t, pos)
        if not m:
            break
        vals.append(int(m.group(1)))
        pos = m.end()
    return vals


def next_line(t, pos):
    i = t.find(b'\n', pos)
    return len(t) if i < 0 else i + 1


def skip_blank_comments(t, pos):
    while pos < len(t):
        while pos < len(t) and t[pos:pos + 1] in (b' ', b'\t', b'\r', b'\n'):
            pos += 1
        if t[pos:pos + 2] == b'//':
            pos = next_line(t, pos)
            continue
        break
    return pos


def is_end(t, pos):
    return t[pos:pos + 3] == b'END'


def next_token(t, pos):
    while pos < len(t) and t[pos:pos + 1] not in (b' ', b'\t', b'\r', b'\n'):
        pos += 1
    while pos < len(t) and t[pos:pos + 1] in (b' ', b'\t'):
        pos += 1
    return pos


def parse(t, mbaacc=False):
    """Parse a vector.txt the way the game does. Returns dict."""
    pos = skip_blank_comments(t, 0)
    vec = {}
    while not is_end(t, pos):
        vid = scan_ints(t, pos, 1)[0]
        v = scan_ints(t, next_token(t, pos), 4)
        vec[vid] = v + [0] * (4 - len(v))
        pos = skip_blank_comments(t, next_line(t, pos))
    pos = skip_blank_comments(t, next_line(t, pos))
    hit = {}
    while not is_end(t, pos):
        hid = scan_ints(t, pos, 1)[0]
        npos = next_token(t, pos)
        sp = t.find(b' ', npos)
        name = t[npos:sp]
        hdr = scan_ints(t, next_token(t, npos), 5)
        hdr += [0] * (5 - len(hdr))
        pos = skip_blank_comments(t, next_line(t, npos))
        rows = []
        for _ in range(max(hdr[0], 0)):
            r = scan_ints(t, pos, 6)
            rows.append(r + [0] * (6 - len(r)))
            pos = skip_blank_comments(t, next_line(t, pos))
        hit[hid] = (name, hdr, rows)
    pos = skip_blank_comments(t, next_line(t, pos))
    stop = scan_ints(t, pos, 7)
    pos = skip_blank_comments(t, next_line(t, pos))
    recoil = scan_ints(t, pos, 1)
    recoil = recoil[0] if recoil else 0
    recoil2 = recoil
    if mbaacc:
        pos = skip_blank_comments(t, next_line(t, pos))
        r2 = scan_ints(t, pos, 1)
        recoil2 = r2[0] if r2 and r2[0] else recoil
    return {'vec': vec, 'hit': hit, 'stop': stop, 'recoil': (recoil, recoil2)}


def flag_digits(v):
    s = '%08d' % v
    if set(s) - {'0', '1'}:
        raise ValueError('flag %d is not a 0/1 digit field' % v)
    return s


def emit(p, src_name):
    L = []
    L.append('// ActCadenza Ver.1.03A vector table (%s) in MBAACC vector.txt syntax.' % src_name)
    L.append('// Generated by tools/ha4/actcadenza_vector.py. Values are ActCadenza\'s; HitAni/GuardAni')
    L.append('// are ActCadenza pattern numbers.')
    L.append('// id  X  Y  AddX  AddY')
    for vid in sorted(p['vec']):
        L.append('%4d %6d %6d %5d %5d' % ((vid,) + tuple(p['vec'][vid])))
    L.append('')
    L.append('END')
    L.append('')
    L.append('// No Name VecCnt UkemiTime Prio PrioAni KoCheck')
    L.append('//      VecNum HitAni GuardAni Time VecTime flag')
    for hid in sorted(p['hit']):
        name, hdr, rows = p['hit'][hid]
        L.append(None)  # placeholder for the byte name
        L[-1] = (b'%3d ' % hid) + name + (' %d %d %d %d %d' % tuple(hdr)).encode()
        for r in rows:
            L.append('  %d %d %d %d %d %s' % (tuple(r[:5]) + (flag_digits(r[5]),)))
    L.append('')
    L.append('END')
    L.append('')
    L.append('// hit stop: weak mid strong none big huge tiny')
    L.append('  ' + ' '.join('%d' % v for v in p['stop']))
    L.append('// wall recoil X; second line = recoil while down (MBAACC only; ActCadenza has one value)')
    L.append('%d' % p['recoil'][0])
    L.append('%d' % p['recoil'][1])
    L.append('')
    L.append('END')
    L.append('')
    out = []
    for x in L:
        out.append(x if isinstance(x, bytes) else x.encode('cp932'))
    return b'\r\n'.join(out)


def selftest(src, out):
    fails = []
    a = parse(src)
    b = parse(out, mbaacc=True)
    if a != b:
        for k in a:
            if a[k] != b[k]:
                fails.append('section %s differs after round trip' % k)
    if len(a['vec']) < 40 or len(a['hit']) < 40:
        fails.append('too few rows: %d vectors, %d hit vectors' % (len(a['vec']), len(a['hit'])))
    if len(a['stop']) != 7:
        fails.append('hit stop has %d values' % len(a['stop']))
    for hid, (name, hdr, rows) in a['hit'].items():
        if len(name) >= 32:
            fails.append('hit %d name is %d bytes (record holds 32)' % (hid, len(name)))
        for r in rows:
            if r[0] not in a['vec'] and r[0] >= 0:
                fails.append('hit %d uses undefined vector %d' % (hid, r[0]))
    # spot checks against the source text
    if a['vec'].get(0) != [900, 0, -70, 0]:
        fails.append('vector 0 = %s' % a['vec'].get(0))
    if 11 in a['hit'] and a['hit'][11][1] != [1, 30, 100, 0, 11]:
        fails.append('hit 11 header %s (expected sscanf carry-over KoCheck 11)' % a['hit'][11][1])
    for f in fails:
        print('FAIL: ' + f)
    print('vectors %d, hit vectors %d, hit stop %s, recoil %s' % (len(a['vec']), len(a['hit']), a['stop'], a['recoil']))
    print('selftest: %s (%d failures)' % ('ok' if not fails else 'FAILED', len(fails)))
    return 0 if not fails else 1


def main(argv):
    args = [a for a in argv if not a.startswith('--')]
    if len(args) != 2:
        print(__doc__)
        return 2
    src = open(args[0], 'rb').read()
    out = emit(parse(src), args[0].replace('\\', '/').split('/')[-1])
    import os
    os.makedirs(os.path.dirname(os.path.abspath(args[1])), exist_ok=True)
    with open(args[1], 'wb') as f:
        f.write(out)
    print('wrote %s (%d B)' % (args[1], len(out)))
    if '--selftest' in argv:
        return selftest(src, open(args[1], 'rb').read())
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
