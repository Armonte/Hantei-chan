#!/usr/bin/env python3
"""Generate src/rhi/d3d9/fx/fx_cp932_table.inc from Python's cp932 codec.

The games' Shader/*.txt files are Shift-JIS (CP932): Japanese comments, and a
trail byte may be 0x5C, so the text has to be decoded before any comment
stripping. The parser is pure C++ (PLAN.md P3 step 1) and has to build and test
on both platforms, so the table is baked in here instead of calling
MultiByteToWideChar.

    python3 tools/fx/gen_cp932.py > src/rhi/d3d9/fx/fx_cp932_table.inc
"""
import sys

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = [t for t in range(0x40, 0xFD) if t != 0x7F]


def single(b):
    try:
        return ord(bytes([b]).decode("cp932"))
    except UnicodeDecodeError:
        return None


def main():
    out = sys.stdout
    out.write("// Generated by tools/fx/gen_cp932.py from Python's cp932 codec. Do not edit.\n")
    out.write("// 0xFFFF marks a byte (or pair) that CP932 does not define.\n\n")

    out.write("static const uint16_t kCp932Single[256] = {\n")
    for b in range(256):
        cp = single(b)
        out.write("\t0x%04X," % (cp if cp is not None else 0xFFFF))
        out.write("\n" if b % 8 == 7 else " ")
    out.write("\n};\n\n")

    out.write("// Base index into kCp932Double for a lead byte, or 0xFFFF when b is not a lead.\n")
    out.write("static const uint16_t kCp932Lead[256] = {\n")
    for b in range(256):
        if b in LEADS:
            base = (b - 0x81 if b < 0xA0 else 31 + (b - 0xE0)) * len(TRAILS)
        else:
            base = 0xFFFF
        out.write("\t0x%04X," % base)
        out.write("\n" if b % 8 == 7 else " ")
    out.write("\n};\n\n")

    out.write("// kCp932Double[kCp932Lead[lead] + trail - 0x40]: the pair's code point.\n")
    out.write("static const uint16_t kCp932Double[%d] = {\n" % (len(LEADS) * len(TRAILS)))
    n = 0
    for lead in LEADS:
        for trail in TRAILS:
            try:
                cp = ord(bytes([lead, trail]).decode("cp932"))
            except UnicodeDecodeError:
                cp = None
            out.write("\t0x%04X," % (cp if cp is not None else 0xFFFF))
            n += 1
            out.write("\n" if n % 8 == 0 else " ")
    out.write("\n};\n")


if __name__ == "__main__":
    main()
